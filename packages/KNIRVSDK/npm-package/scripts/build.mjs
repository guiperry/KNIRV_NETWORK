import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const output = resolve(root, "wasm");
const modulesOutput = resolve(root, "modules");
const coreAssets = resolve(root, "../core/wasm-modules/assets");
rmSync(output, { recursive: true, force: true });
mkdirSync(output, { recursive: true });

execFileSync("wasm-pack", ["build", "wasm-core", "--target", "web", "--release", "--out-dir", "../wasm", "--out-name", "knirv_sdk_core"], { cwd: root, stdio: "inherit" });
// wasm-pack writes `wasm/.gitignore` containing `*`; npm honors it even when
// package.json explicitly includes wasm/, so remove this generated file.
rmSync(resolve(output, ".gitignore"), { force: true });

const binary = readFileSync(resolve(output, "knirv_sdk_core_bg.wasm"));
writeFileSync(resolve(output, "inlined_base64.js"), `// Generated by scripts/build.mjs; do not edit.\nconst base64 = "${binary.toString("base64")}";\nexport const inlinedWasmBytes = Uint8Array.from(atob(base64), char => char.charCodeAt(0));\n`);
writeFileSync(resolve(output, "inlined_base64.d.ts"), "export declare const inlinedWasmBytes: Uint8Array;\n");

// One manifest, generated by the SDK build (scripts/sdk-dist.mjs) from
// core/wasm-modules/modules.json plus the built bytes. Nothing is described here.
const sourceManifest = JSON.parse(readFileSync(resolve(root, "../core/wasm-modules/manifest.json"), "utf8"));
rmSync(modulesOutput, { recursive: true, force: true });
mkdirSync(modulesOutput, { recursive: true });
const modules = sourceManifest.modules;
for (const m of modules) {
  const source = resolve(coreAssets, `${m.id}.wasm`);
  const bytes = readFileSync(source);
  if (createHash("sha256").update(bytes).digest("hex") !== m.sha256) throw new Error(`${m.id}: asset does not match core/wasm-modules/manifest.json; run \`make build-wasm\``);
  copyFileSync(source, resolve(modulesOutput, `${m.id}.wasm`));
}
writeFileSync(resolve(modulesOutput, "manifest.json"), `${JSON.stringify({ version: 1, modules }, null, 2)}\n`);
const coreVersion = /^version\s*=\s*"([^"]+)"/m.exec(readFileSync(resolve(root, "../core/Cargo.toml"), "utf8"))[1];
writeFileSync(resolve(modulesOutput, "manifest.js"), `// Generated by scripts/build.mjs; do not edit.\nexport const wasmModulesManifest = ${JSON.stringify({ version: 1, modules })};\nexport const wasmModulesReleaseVersion = ${JSON.stringify(coreVersion)};\n`);
writeFileSync(resolve(modulesOutput, "manifest.d.ts"), "import type { WasmModuleManifest } from '../modules.js';\nexport declare const wasmModulesManifest: WasmModuleManifest;\nexport declare const wasmModulesReleaseVersion: string;\n");

// The wallet extension's message protocol (request kinds, success/failure/reject
// outcomes, codes and messages) is written once in core/data/wallet_protocol.json;
// generate its TypeScript constants so @knirv/sdk/wallet carries no second copy.
const protocol = JSON.parse(readFileSync(resolve(root, "../core/data/wallet_protocol.json"), "utf8"));
const families = Object.fromEntries(["execute", "success", "failure", "reject"].map((f) => [f, Object.keys(protocol[f])]));
const messages = Object.fromEntries(Object.values(["execute", "success", "failure", "reject"]).flatMap((f) => Object.entries(protocol[f]).map(([key, [code, message]]) => [key, { code, message, type: key }])));
const constObject = (keys) => `{\n${keys.map((k) => `  ${k}: ${JSON.stringify(k)},`).join("\n")}\n} as const`;
mkdirSync(resolve(root, "src/wallet"), { recursive: true });
writeFileSync(
  resolve(root, "src/wallet/protocol.generated.ts"),
  `// Generated by scripts/build.mjs from core/data/wallet_protocol.json; do not edit.
export const WalletResponseExecuteType = ${constObject(families.execute)};
export const WalletResponseSuccessType = ${constObject(families.success)};
export const WalletResponseFailureType = ${constObject(families.failure)};
export const WalletResponseRejectType = ${constObject(families.reject)};
export const walletMessages = ${JSON.stringify(messages, null, 2)} as const;
`,
);
