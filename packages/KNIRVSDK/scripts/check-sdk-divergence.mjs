#!/usr/bin/env node
// Divergence gate for the KNIRVSDK. The Rust core (core/) is the single source of
// truth; the Go and TypeScript packages are bindings. This script fails the build
// (exit 1) when the tree drifts from that rule:
//
//   V-VERSION        the core, WASI binding, wasm-core, Go stamp and npm package do
//                    not all carry the same version (core/Cargo.toml is canonical).
//   V-LOCK           a Cargo.lock pins a different version of an SDK crate.
//   R-NATIVE-CRYPTO  Go or TS wrapper code computes a cryptographic primitive
//                    (hash, MAC, signature, KDF, cipher, curve math) itself.
//   R-OP-UNKNOWN     a wrapper calls a binding operation the core does not define.
//   R-DUP-LIST       a wrapper re-declares an allowlist or table that the core owns.
//
// Every finding prints file:line, language and enclosing function, plus where the
// change belongs. A deliberate host-side exception must be listed, with a reason,
// in scripts/divergence-allowlist.json. A listed exception that no longer matches
// any finding is an error too, so the list cannot rot.
//
// Usage: node scripts/check-sdk-divergence.mjs [--quiet]
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const quiet = process.argv.includes("--quiet");
const rel = (p) => relative(root, p).split(sep).join("/");
const read = (p) => readFileSync(resolve(root, p), "utf8");
const lineOf = (text, index) => text.slice(0, index).split("\n").length;

const findings = []; // {rule, lang, file, line, fn, message, fix}
const add = (f) => findings.push(f);

// ---------------------------------------------------------------- V-VERSION --
// Every place a version is written down, with the file and line it lives on.
function versionSources() {
  const out = [];
  const cargo = (path, lang, label) => {
    const text = read(path);
    const m = /^version\s*=\s*"([^"]+)"/m.exec(text);
    if (m) out.push({ lang, file: path, line: lineOf(text, m.index), symbol: label, version: m[1] });
  };
  cargo("core/Cargo.toml", "Rust", "[package] version (canonical)");
  cargo("bindings/wasi/Cargo.toml", "Rust", "[package] version (WASI binding)");
  cargo("npm-package/wasm-core/Cargo.toml", "Rust", "[package] version (wasm-bindgen core)");

  const goStamp = "go-package/internal/core/stamp.go";
  const g = read(goStamp);
  const gm = /Version\s*=\s*"([^"]+)"/.exec(g);
  if (gm) out.push({ lang: "Go", file: goStamp, line: lineOf(g, gm.index), symbol: "const Version", version: gm[1] });

  const pkg = "npm-package/package.json";
  const p = read(pkg);
  const pm = /^\s*"version":\s*"([^"]+)"/m.exec(p);
  if (pm) out.push({ lang: "TypeScript", file: pkg, line: lineOf(p, pm.index), symbol: '"version" (@knirv/sdk)', version: pm[1] });

  const core = "npm-package/core.json";
  const c = read(core);
  const cm = /"version":\s*"([^"]+)"/.exec(c);
  if (cm) out.push({ lang: "TypeScript", file: core, line: lineOf(c, cm.index), symbol: '"version" (npm core stamp)', version: cm[1] });

  const wasmPkg = "npm-package/wasm/package.json"; // generated by wasm-pack; checked when present
  if (existsSync(resolve(root, wasmPkg))) {
    const w = read(wasmPkg);
    const wm = /^\s*"version":\s*"([^"]+)"/m.exec(w);
    if (wm) out.push({ lang: "TypeScript", file: wasmPkg, line: lineOf(w, wm.index), symbol: '"version" (wasm-pack output)', version: wm[1] });
  }
  return out;
}

function checkVersions() {
  const sources = versionSources();
  const canonical = sources[0];
  for (const s of sources) {
    if (s.version === canonical.version) continue;
    add({
      rule: "V-VERSION", lang: s.lang, file: s.file, line: s.line, fn: s.symbol,
      message: `version ${s.version} but ${canonical.file}:${canonical.line} (Rust core) says ${canonical.version}`,
      fix: s.lang === "Go"
        ? `set Version in ${s.file} (or run \`make stamp\`, which writes it from core/Cargo.toml)`
        : `set ${s.symbol} in ${s.file} to ${canonical.version}`,
    });
  }
  // Cargo.lock must agree with the crate it pins. Only lock files that list the crate.
  const crates = { "core/Cargo.lock": "knirv-sdk", "bindings/wasi/Cargo.lock": "knirv-sdk-wasi", "npm-package/wasm-core/Cargo.lock": "knirv-sdk-wasm-core" };
  for (const [lock, name] of Object.entries(crates)) {
    if (!existsSync(resolve(root, lock))) continue;
    const text = read(lock);
    const re = new RegExp(`name = "${name}"\\nversion = "([^"]+)"`);
    const m = re.exec(text);
    if (!m) continue;
    const want = sources.find((s) => s.lang === "Rust" && s.file.endsWith(`${name === "knirv-sdk" ? "core" : name === "knirv-sdk-wasi" ? "bindings/wasi" : "npm-package/wasm-core"}/Cargo.toml`))?.version ?? canonical.version;
    if (m[1] !== want) {
      add({
        rule: "V-LOCK", lang: "Rust", file: lock, line: lineOf(text, m.index), fn: `package ${name}`,
        message: `Cargo.lock pins ${name} ${m[1]}, its Cargo.toml says ${want}`,
        fix: `run cargo update -p ${name} --manifest-path ${lock.replace("Cargo.lock", "Cargo.toml")} (offline is fine for a version-only change)`,
      });
    }
  }
}

// --------------------------------------------------------------- file walk --
function walk(dir, keep, out = []) {
  for (const name of readdirSync(dir)) {
    if (["node_modules", "target", "dist", "testdata", "vendor", ".git"].includes(name)) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, keep, out);
    else if (keep(p)) out.push(p);
  }
  return out;
}
const isGoSource = (p) => p.endsWith(".go") && !p.endsWith("_test.go");
const isTsSource = (p) => p.endsWith(".ts") && !p.endsWith(".test.ts") && !p.endsWith(".d.ts");
const goFiles = walk(resolve(root, "go-package"), isGoSource);
const tsFiles = existsSync(resolve(root, "npm-package/src")) ? walk(resolve(root, "npm-package/src"), isTsSource) : [];

// Comments do not count as code. Blank out // and /* */ bodies (keeping newlines so
// line numbers survive) before scanning. Strings are kept (the op checks need them).
function stripComments(text, lang) {
  let out = text.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "));
  out = out.split("\n").map((l) => {
    const i = l.indexOf("//");
    // A "//" inside a string literal (e.g. "https://") is not a comment.
    if (i < 0 || /["'`][^"'`]*\/\/[^"'`]*["'`]/.test(l)) return l;
    return l.slice(0, i);
  }).join("\n");
  return out;
}

// Name of the function enclosing a 1-based line: nearest preceding declaration.
const GO_FUNC = /^func\s+(?:\(\s*\w*\s*\*?\s*(\w+)[^)]*\)\s*)?(\w+)\s*\(/;
const TS_FUNCS = [
  /^\s*(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_$][\w$]*)/,
  /^\s*(?:export\s+)?const\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s*)?(?:\([^)]*\)|[A-Za-z_$][\w$]*)\s*(?::[^=]+)?=>/,
  /^\s*(?:(?:public|private|protected|static|async|override|readonly)\s+)*([A-Za-z_$][\w$]*)\s*(?:<[^>]*>)?\s*\([^)]*\)\s*(?::\s*[^{]+)?\{\s*$/,
];
const NOT_FN = new Set(["if", "for", "while", "switch", "catch", "return", "constructor"]);
function enclosingFn(lines, lineNo, lang) {
  for (let i = lineNo - 1; i >= 0; i--) {
    const l = lines[i];
    if (lang === "Go") {
      const m = GO_FUNC.exec(l);
      if (m) {
        const recv = /^func\s+\(\s*\w*\s*\*?\s*(\w+)/.exec(l);
        return recv ? `${recv[1]}.${m[2]}` : m[2];
      }
    } else {
      for (const re of TS_FUNCS) {
        const m = re.exec(l);
        if (m && !NOT_FN.has(m[1])) return m[1];
      }
    }
  }
  return "(package scope)";
}

// Where a primitive should be implemented instead, by the package or module it sits in.
function coreHome(file) {
  const table = [
    ["dveevidence", "evidence"], ["secrets", "secrets"], ["authority", "authority"], ["signing", "signing"],
    ["uri", "uri"], ["replication", "replication"], ["models", "models"], ["internal/core", "lib"],
  ];
  for (const [needle, stem] of table) {
    if (file.includes(`/${needle}/`) || file.startsWith(`go-package/${needle}/`)) {
      const path = `core/src/${stem}.rs`;
      return existsSync(resolve(root, path)) ? path : `${path} (new module, or an existing one)`;
    }
  }
  const base = file.split("/").pop().replace(/\.ts$/, "");
  const path = `core/src/${base}.rs`;
  return existsSync(resolve(root, path)) ? path : `core/src (the module owning ${base}; add a binding op in core/src/bindings/ops.rs)`;
}

// ------------------------------------------------------------- V-DIGEST --
// The Go stamp (WASI core) and npm core.json (web core) are the published pins.
// Every tracked copy of the core must match them. Gitignored build outputs in
// KNIRVARENA / KNIRV_CORP are reported as warnings, never failures.
const warnings = [];
const sha256File = (p) => createHash("sha256").update(readFileSync(p)).digest("hex");

function findWasm(dir, depth = 0) {
  if (depth > 8 || !existsSync(dir)) return [];
  const out = [];
  let names;
  try { names = readdirSync(dir); } catch { return out; }
  for (const name of names) {
    if (["node_modules", ".git", "target", "build", "Pods", ".gradle", "DerivedData"].includes(name)) continue;
    const p = join(dir, name);
    let st;
    try { st = statSync(p); } catch { continue; }
    if (st.isDirectory()) out.push(...findWasm(p, depth + 1));
    else if (/knirv(_sdk)?_core.*\.wasm$/i.test(name) || /knirv_core\.wasm$/i.test(name)) out.push(p);
  }
  return out;
}

function checkDigestPins() {
  const go = read("go-package/internal/core/stamp.go");
  const version = /Version\s*=\s*"([^"]+)"/.exec(go)?.[1] ?? versionSources()[0].version;
  const wasi = /Digest\s*=\s*"([0-9a-f]{64})"/.exec(go)?.[1];
  if (!wasi) {
    add({ rule: "V-DIGEST", lang: "Go", file: "go-package/internal/core/stamp.go", line: 1, fn: "const Digest",
      message: "stamp.go has no 64-hex Digest; the Go binding is not pinned to a published core",
      fix: "run `make stamp` from the release checkout (or restore the published digest)" });
    return;
  }
  const npm = JSON.parse(read("npm-package/core.json"));
  const web = npm.sha256;
  for (const [file, want, label] of [
    [`dist/${version}/knirv_core.wasm`, wasi, "WASI core (release dist)"],
    ["../KNIRVSERVER/pkg/embedded/knirvbao/plugin/assets/knirv_core.wasm", wasi, "WASI core (KNIRVSERVER embedded)"],
    ["npm-package/wasm/knirv_sdk_core_bg.wasm", web, "web core (npm inline)"],
  ]) {
    const abs = resolve(root, file);
    if (!existsSync(abs)) continue;
    const got = sha256File(abs);
    if (got === want) continue;
    add({ rule: "V-DIGEST", lang: "-", file, line: 1, fn: label,
      message: `sha256 ${got.slice(0, 16)}… != pinned ${want.slice(0, 16)}… (${label})`,
      fix: `replace this copy with the published ${label.startsWith("web") ? "web" : "WASI"} core, or re-stamp deliberately (make stamp) and update every copy` });
  }
  // Stale build outputs outside the SDK are an owner item, not a build failure.
  for (const [dir, note] of [
    [resolve(root, "../KNIRVARENA"), "gitignored KNIRVARENA build output"],
    [resolve(root, "../../../KNIRV_CORP"), "gitignored KNIRV_CORP build output"],
  ]) {
    for (const p of findWasm(dir)) {
      let got;
      try { got = sha256File(p); } catch { continue; }
      if (got === wasi || got === web) continue;
      warnings.push(`${note}: ${relative(resolve(root, "../../.."), p).split(sep).join("/")} sha256 ${got.slice(0, 12)}… (pinned ${wasi.slice(0, 12)}… / ${web.slice(0, 12)}…) — owner item; rebuild that tree when it settles`);
    }
  }
}

// ---------------------------------------------------------- R-NATIVE-CRYPTO --
const GO_PRIMITIVE_CALL = /\b(sha256|sha512|sha1|md5|hmac|ed25519|ecdsa|ecdh|elliptic|rsa|aes|cipher|scrypt|argon2|pbkdf2|hkdf|chacha20poly1305|secp256k1|bip39|bip32|dcrec\w*|btcec\w*)\.(New\w*|Sum\w*|Sign\w*|Verify\w*|Generate\w*|NewKeyFromSeed|Key|Derive\w*|Seal|Open)\(/;
const GO_PRIMITIVE_IMPORT = /^\s*(?:\w+\s+)?"(golang\.org\/x\/crypto\/[^"]+|github\.com\/(?:decred|btcsuite)\/[^"]+)"/;
const GO_PRIMITIVE_DEF = /^func\s+(?:\([^)]*\)\s*)?(sha\d*\w*|hmac\w*|ed25519\w*|ecdsa\w*|secp256k1\w*|scrypt\w*|argon2\w*|pbkdf2\w*|hkdf\w*)\s*\(/i;
const TS_PRIMITIVE_IMPORT = /from\s+['"](?:node:)?crypto['"]|from\s+['"]@noble\/|from\s+['"]@scure\/|from\s+['"](?:tweetnacl|elliptic|secp256k1|js-sha256|crypto-js)['"]/;
const TS_PRIMITIVE_CALL = /\bcrypto\.subtle\.(?:digest|sign|verify|importKey|exportKey|encrypt|decrypt|deriveBits|deriveKey|generateKey|wrapKey|unwrapKey)\s*\(|\b(?:createHash|createHmac|createCipheriv|createDecipheriv|scryptSync|pbkdf2Sync|pbkdf2)\s*\(/;
const TS_PRIMITIVE_DEF = /^\s*(?:export\s+)?function\s+(sha\d*\w*|hmac\w*|ed25519\w*|secp256k1\w*|scrypt\w*|pbkdf2\w*|hkdf\w*|keccak\w*)\s*\(/i;

function scanPrimitives(file, lang, text) {
  const lines = stripComments(text, lang).split("\n");
  lines.forEach((l, i) => {
    const n = i + 1;
    const hit = (what, re) => add({
      rule: "R-NATIVE-CRYPTO", lang, file, line: n, fn: enclosingFn(lines, n, lang),
      message: `${what}: \`${l.trim().slice(0, 110)}\``,
      fix: `move this computation into ${coreHome(file)} as a binding op, then call it from ${lang} (pattern: go-package/secrets/raw_contract.go)`,
    });
    if (lang === "Go") {
      if (GO_PRIMITIVE_CALL.test(l)) hit("native cryptographic primitive call", GO_PRIMITIVE_CALL);
      else if (GO_PRIMITIVE_DEF.test(l)) hit("native cryptographic primitive defined in Go", GO_PRIMITIVE_DEF);
      else if (GO_PRIMITIVE_IMPORT.test(l)) hit("native cryptography package imported", GO_PRIMITIVE_IMPORT);
    } else {
      if (TS_PRIMITIVE_IMPORT.test(l)) hit("native cryptography package imported", TS_PRIMITIVE_IMPORT);
      else if (TS_PRIMITIVE_CALL.test(l)) hit("native cryptographic primitive call", TS_PRIMITIVE_CALL);
      else if (TS_PRIMITIVE_DEF.test(l)) hit("native cryptographic primitive defined in TypeScript", TS_PRIMITIVE_DEF);
    }
  });
}

// ------------------------------------------------------------ R-OP-UNKNOWN --
// Operations are dispatched from several core modules (bindings.rs, bindings/ops.rs,
// frame.rs, vault.rs, ...), so the table is every "family.op" string literal the
// core source defines. A wrapper op that appears in no core file is a divergence.
const coreOps = new Set();
for (const f of walk(resolve(root, "core/src"), (p) => p.endsWith(".rs"))) {
  for (const m of readFileSync(f, "utf8").matchAll(/"([a-z][a-z0-9_]*\.[a-z0-9_.]+)"/g)) coreOps.add(m[1]);
}

const OP_CALL = /\b(call|callLocal|callLocalEnvelope|mustCore|evidence)(?:<[^>(]*>)?\(\s*["'`]([a-z][a-z0-9_]*\.[a-z0-9_.]+)["'`]/g;
function scanOps(file, lang, text) {
  const code = stripComments(text, lang);
  for (const m of code.matchAll(OP_CALL)) {
    const op = m[2];
    if (coreOps.has(op)) continue;
    const line = lineOf(code, m.index);
    add({
      rule: "R-OP-UNKNOWN", lang, file, line, fn: enclosingFn(code.split("\n"), line, lang),
      message: `binding op "${op}" is not defined in any core source file (core/src/**)`,
      fix: `add the op to the core dispatch (core/src/bindings.rs or the owning module), or call an op the core already exposes`,
    });
  }
}

// ------------------------------------------------------------- R-DUP-LIST --
// Allowlists and tables the core owns: `pub const NAME: &[&str] = &[ ... ];`
const coreLists = new Map();
for (const f of walk(resolve(root, "core/src"), (p) => p.endsWith(".rs"))) {
  const text = readFileSync(f, "utf8");
  for (const m of text.matchAll(/pub const ([A-Z_]+): &\[&str\] = &\[([\s\S]*?)\];/g)) {
    const values = [...m[2].matchAll(/"([^"]+)"/g)].map((v) => v[1]);
    if (values.length) coreLists.set(m[1], { values, source: `${rel(f)}` });
  }
}
function scanDuplicatedLists(file, lang, text) {
  const lines = stripComments(text, lang).split("\n");
  lines.forEach((l, i) => {
    for (const [name, { values, source }] of coreLists) {
      const present = values.filter((v) => l.includes(`"${v}"`) || l.includes(`'${v}'`));
      if (!present.length) continue;
      const inLiteral = /[[{]/.test(l.slice(0, Math.min(...present.map((v) => l.indexOf(v)).filter((x) => x >= 0)) + 1));
      // Two or more values of one core list on a line is a copied table. A single value
      // is only a finding for an allowlist (a word like "prompt" is also a JSON key).
      if (present.length >= 2 || (inLiteral && /ALLOWED/.test(name))) {
        add({
          rule: "R-DUP-LIST", lang, file, line: i + 1, fn: enclosingFn(lines, i + 1, lang),
          message: `re-declares the core list ${name} (${source}): \`${l.trim().slice(0, 110)}\``,
          fix: `read the list from the core through a binding op instead of copying it into ${lang}`,
        });
      }
    }
  });
}

// ----------------------------------------------------------------- run --
checkVersions();
checkDigestPins();
for (const f of goFiles) scanPrimitives(rel(f), "Go", readFileSync(f, "utf8"));
for (const f of tsFiles) scanPrimitives(rel(f), "TypeScript", readFileSync(f, "utf8"));
for (const f of goFiles) { scanOps(rel(f), "Go", readFileSync(f, "utf8")); scanDuplicatedLists(rel(f), "Go", readFileSync(f, "utf8")); }
for (const f of tsFiles) { scanOps(rel(f), "TypeScript", readFileSync(f, "utf8")); scanDuplicatedLists(rel(f), "TypeScript", readFileSync(f, "utf8")); }

// ------------------------------------------------------------ allowlist --
const allowPath = "scripts/divergence-allowlist.json";
const allow = existsSync(resolve(root, allowPath)) ? JSON.parse(read(allowPath)).entries ?? [] : [];
const used = new Set();
const allowed = [];
const failures = [];
for (const f of findings) {
  const idx = allow.findIndex((e) => e.file === f.file && e.rule === f.rule && (e.function === undefined || e.function === f.fn));
  if (idx >= 0) {
    used.add(idx);
    allowed.push({ ...f, reason: allow[idx].reason, tracking: allow[idx].tracking });
  } else failures.push(f);
}
allow.forEach((e, i) => {
  if (!used.has(i)) {
    failures.push({
      rule: "A-STALE", lang: "-", file: allowPath, line: 1, fn: `${e.file} ${e.function ?? "*"} ${e.rule}`,
      message: "allowlist entry matches no finding; remove it (the divergence was fixed)",
      fix: `delete this entry from ${allowPath}`,
    });
  }
});

const fmt = (f) => `${f.file}:${f.line}  [${f.lang}] ${f.fn}  (${f.rule})\n    ${f.message}\n    change needed: ${f.fix}`;
if (!quiet && allowed.length) {
  console.log(`sdk divergence: ${allowed.length} listed exception(s) in ${allowPath}:`);
  for (const a of allowed) console.log(`  ~ ${a.file}:${a.line} [${a.lang}] ${a.fn} (${a.rule}) tracking: ${a.tracking ?? "-"}`);
}
if (failures.length) {
  console.error(`sdk divergence check FAILED: ${failures.length} problem(s)\n`);
  for (const f of failures) console.error(`${fmt(f)}\n`);
  console.error("Fix the source, or (for a deliberate host-side exception only) add an entry with a reason to scripts/divergence-allowlist.json.");
  process.exit(1);
}
console.log(`sdk divergence check: versions aligned (${versionSources()[0].version}), ${goFiles.length} Go and ${tsFiles.length} TypeScript wrapper files clean (${allowed.length} listed exception(s)).`);
if (warnings.length) {
  console.log(`\nsdk divergence warnings (${warnings.length}, advisory):`);
  for (const w of warnings) console.log(`  ! ${w}`);
}
