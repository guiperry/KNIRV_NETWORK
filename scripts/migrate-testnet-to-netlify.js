#!/usr/bin/env node

/**
 * KNIRV Testnet to Netlify Migration Script
 * Migrates KNIRVTESTNET contents to KNIRVGATEWAY/knirvtestnet
 * Configures Server-Side Execution (SSE) endpoints for Netlify
 */

const fs = require('fs');
const path = require('path');

// Colors for console output (from existing script)
const colors = {
  green: '\x1b[32m',
  red: '\x1b[31m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  cyan: '\x1b[36m',
  reset: '\x1b[0m'
};

function log(message, color = 'reset') {
  console.log(`${colors[color]}${message}${colors.reset}`);
}

// Configuration
const BASE_DIR = path.join(process.cwd(), '..'); // Go up to cloud-equities
const SOURCE_DIR = path.join(process.cwd(), 'KNIRVTESTNET');
const DEST_DIR = path.join(BASE_DIR, 'KNIRV_NETWORK/KNIRVGATEWAY/knirvtestnet');
const NETLIFY_FUNCTIONS_DIR = path.join(BASE_DIR, 'KNIRV_NETWORK/KNIRVGATEWAY/netlify/functions');
const NETLIFY_TOML_PATH = path.join(BASE_DIR, 'KNIRV_NETWORK/KNIRVGATEWAY/netlify.toml');

// Ensure directories exist
function ensureDirectories() {
  if (!fs.existsSync(DEST_DIR)) {
    fs.mkdirSync(DEST_DIR, { recursive: true });
    log(`📁 Created destination directory: ${DEST_DIR}`, 'green');
  }

  if (!fs.existsSync(NETLIFY_FUNCTIONS_DIR)) {
    fs.mkdirSync(NETLIFY_FUNCTIONS_DIR, { recursive: true });
    log(`📁 Created Netlify functions directory: ${NETLIFY_FUNCTIONS_DIR}`, 'green');
  }
}

// Copy directory recursively
function copyDirectory(source, destination) {
  // Check if source exists
  if (!fs.existsSync(source)) {
    log(`⚠️  Source directory not found: ${source}`, 'yellow');
    return;
  }

  // Create destination directory if it doesn't exist
  if (!fs.existsSync(destination)) {
    fs.mkdirSync(destination, { recursive: true });
  }

  // Read source directory
  const files = fs.readdirSync(source);

  for (const file of files) {
    const srcPath = path.join(source, file);
    const destPath = path.join(destination, file);
    
    try {
      const stat = fs.statSync(srcPath);

      if (stat.isDirectory()) {
        copyDirectory(srcPath, destPath);
      } else if (!fs.existsSync(destPath)) { // Only copy if destination doesn't exist
        fs.copyFileSync(srcPath, destPath);
        log(`📄 Copied: ${file}`, 'cyan');
      } else {
        log(`⏩ Skipped existing file: ${file}`, 'yellow');
      }
    } catch (error) {
      log(`⚠️  Error processing ${file}: ${error.message}`, 'yellow');
    }
  }
}

// Generate SSE endpoint handler
function generateSSEEndpoint() {
  const sseContent = `// Testnet SSE Endpoint
const handler = async (event, context) => {
  // Set SSE headers
  const headers = {
    'Content-Type': 'text/event-stream',
    'Cache-Control': 'no-cache',
    'Connection': 'keep-alive',
    'Access-Control-Allow-Origin': '*'
  };

  return {
    statusCode: 200,
    headers,
    body: 'SSE connection established for testnet'
  };
};

exports.handler = handler;`;

  const ssePath = path.join(NETLIFY_FUNCTIONS_DIR, 'testnet-sse.js');
  fs.writeFileSync(ssePath, sseContent);
  log(`✅ Created SSE endpoint: ${ssePath}`, 'green');
}

// Update netlify.toml configuration
function updateNetlifyConfig() {
  try {
    let tomlContent = '';
    
    // Read existing config if it exists
    if (fs.existsSync(NETLIFY_TOML_PATH)) {
      tomlContent = fs.readFileSync(NETLIFY_TOML_PATH, 'utf8');
    } else {
      log(`⚠️  Netlify.toml not found at ${NETLIFY_TOML_PATH}`, 'yellow');
      return;
    }

    // Backup original content
    const originalContent = tomlContent;

    // Add testnet build context if not already present
    if (!tomlContent.includes('[context.testnet]')) {
      const testnetConfig = `

# Testnet configuration (auto-generated by migration script)
[context.testnet]
  base = "knirvtestnet/"
  publish = "knirvtestnet/"
  command = "echo 'Testnet static files - no build needed'"

  [context.testnet.environment]
    NODE_ENV = "production"
    VITE_API_BASE_URL = "/.netlify/functions"
    VITE_SSE_BASE_URL = "/.netlify/functions/testnet-sse"
    VITE_TESTNET_MODE = "true"`;

      tomlContent += testnetConfig;
    }

    // Add testnet redirect rules if not present
    if (!tomlContent.includes('/api/testnet/')) {
      const redirectRules = `

# Testnet redirect rules (auto-generated by migration script)
[[redirects]]
  from = "/testnet/*"
  to = "/knirvtestnet/:splat"
  status = 200

[[redirects]]
  from = "/api/testnet/*"
  to = "/.netlify/functions/testnet-sse"
  status = 200`;

      // Insert before the final headers section if it exists
      const headersIndex = tomlContent.lastIndexOf('[[headers]]');
      if (headersIndex !== -1) {
        tomlContent = tomlContent.slice(0, headersIndex) + redirectRules + '\n\n' + tomlContent.slice(headersIndex);
      } else {
        tomlContent += redirectRules;
      }
    }

    // Only write if content changed
    if (tomlContent !== originalContent) {
      fs.writeFileSync(NETLIFY_TOML_PATH, tomlContent);
      log(`✅ Updated Netlify configuration: ${NETLIFY_TOML_PATH}`, 'green');
    } else {
      log(`⏩ Netlify.toml already contains testnet configuration`, 'yellow');
    }
  } catch (error) {
    log(`⚠️  Error updating Netlify.toml: ${error.message}`, 'red');
  }
}

// Main migration function
async function migrateTestnet() {
  try {
    log('🚀 Starting KNIRV Testnet to Netlify Migration', 'blue');
    log('==============================================', 'blue');

    // 1. Ensure directories exist
    ensureDirectories();

    // 2. Copy testnet files
    log('\n📂 Copying testnet files...', 'cyan');
    copyDirectory(SOURCE_DIR, DEST_DIR);

    // 3. Generate SSE endpoint
    log('\n⚡ Setting up SSE endpoint...', 'cyan');
    generateSSEEndpoint();

    // 4. Update Netlify configuration
    log('\n⚙️  Updating Netlify configuration...', 'cyan');
    updateNetlifyConfig();

    log('\n🎉 Migration completed successfully!', 'green');
    return true;

  } catch (error) {
    log(`💥 Migration failed: ${error.message}`, 'red');
    console.error(error);
    return false;
  }
}

// Run if called directly
if (require.main === module) {
  migrateTestnet()
    .then(success => {
      process.exit(success ? 0 : 1);
    });
}

module.exports = { migrateTestnet };
