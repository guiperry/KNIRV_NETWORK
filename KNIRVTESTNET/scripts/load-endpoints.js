#!/usr/bin/env node

/**
 * KNIRVTESTNET Endpoint Loader
 *
 * This script reads endpoints.yaml (if it exists) and sets up environment variables
 * for Render deployment. For testnet, it uses .env.testnet instead.
 *
 * Usage:
 *   node scripts/load-endpoints.js [environment]
 *
 * Environment:
 *   - production: Reads config/endpoints.yaml
 *   - testnet: Uses .env.testnet (default for KNIRVTESTNET)
 *   - development: Uses default development endpoints
 */

const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');
const ConfigLoader = require('./config-loader');

// Default development endpoints
const DEFAULT_ENDPOINTS = {
  KNIRVCHAIN_API: 'http://localhost:8080',
  KNIRVGRAPH_API: 'http://localhost:8081',
  KNIRVNEXUS_API: 'http://localhost:8082',
  KNIRVORACLE_API: 'http://localhost:1317',
  KNIRVROUTER_API: 'http://localhost:8086',
  KNIRVANA_API: 'http://localhost:3000',
  KNIRVANA_INTERACTIVE_GRAPH: 'http://localhost:3000'
};

function loadEndpoints(environment = 'testnet') {
  const testnetRoot = path.resolve(__dirname, '..');
  let endpoints = { ...DEFAULT_ENDPOINTS };
  let config = {
    NODE_ENV: environment,
    DEPLOYMENT_ENV: environment,
    TESTNET_MODE: environment === 'testnet',
    DEBUG_MODE: environment !== 'production',
    ENABLE_CORS: environment !== 'production'
  };

  console.log(`🔧 Loading endpoints for environment: ${environment}`);

  try {
    if (environment === 'production') {
      // Load from endpoints.yaml for production
      const endpointsFile = path.join(testnetRoot, 'config', 'endpoints.yaml');

      if (fs.existsSync(endpointsFile)) {
        console.log('📄 Reading production endpoints from config/endpoints.yaml');
        const yamlContent = fs.readFileSync(endpointsFile, 'utf8');
        const yamlData = yaml.load(yamlContent);

        if (yamlData && yamlData.endpoints) {
          endpoints = { ...endpoints, ...yamlData.endpoints };
          console.log('✅ Production endpoints loaded successfully');
        }

        if (yamlData && yamlData.config) {
          config = { ...config, ...yamlData.config };
        }
      } else {
        console.warn('⚠️  Production endpoints.yaml not found - using defaults');
        console.warn('   Run "make generate-production-endpoints" first');
      }

    } else if (environment === 'testnet') {
      // Load from consolidated config files using ConfigLoader
      console.log('📄 Reading testnet configuration from config files');

      const configLoader = new ConfigLoader(environment);

      // Load endpoints from config
      const serviceEndpoints = configLoader.getServiceEndpoints();
      endpoints = { ...endpoints, ...serviceEndpoints };

      // Load configuration parameters
      const flatConfig = configLoader.getFlatConfig();
      config = { ...config, ...flatConfig };

      console.log('✅ Testnet configuration loaded from config files');

      // Load environment variables from .env.testnet (for runtime variables only)
      const testnetEnvFile = path.join(testnetRoot, '.env.testnet');
      if (fs.existsSync(testnetEnvFile)) {
        const envContent = fs.readFileSync(testnetEnvFile, 'utf8');

        // Parse .env format for environment variables only (NO endpoints or ports)
        envContent.split('\n').forEach(line => {
          const trimmed = line.trim();
          if (trimmed && !trimmed.startsWith('#')) {
            const [key, ...valueParts] = trimmed.split('=');
            const value = valueParts.join('=');
            if (key && value) {
              // Only load true environment variables - NO endpoints, ports, or configuration
              const envVars = ['NODE_ENV', 'DEPLOYMENT_ENV', 'JWT_SECRET'];
              if (envVars.includes(key)) {
                config[key] = value;
              }
            }
          }
        });

        console.log('✅ Environment variables loaded from .env.testnet (secrets only)');
      }
    }

  } catch (error) {
    console.error('❌ Error loading configuration:', error.message);
    console.log('📋 Using default development configuration');
  }

  return { endpoints, config };
}

function generateConfigFiles(endpoints, config) {
  const testnetRoot = path.resolve(__dirname, '..');
  
  try {
    // Generate GraphChain Explorer config
    const graphchainConfig = `// KNIRVTESTNET GraphChain Explorer Configuration
// Auto-generated by load-endpoints.js
// Environment: ${config.DEPLOYMENT_ENV}

window.KNIRV_CONFIG = {
  environment: '${config.DEPLOYMENT_ENV}',
  apiEndpoints: {
    chain: '${endpoints.KNIRVCHAIN_API}',
    graph: '${endpoints.KNIRVGRAPH_API}',
    nexus: '${endpoints.KNIRVNEXUS_API}',
    oracle: '${endpoints.KNIRVORACLE_API}',
    router: '${endpoints.KNIRVROUTER_API}',
    knirvana: '${endpoints.KNIRVANA_API}'
  },
  features: {
    interactiveGraph: true,
    interactiveGraphUrl: '${endpoints.KNIRVANA_INTERACTIVE_GRAPH}',
    testnetMode: ${config.TESTNET_MODE},
    debugMode: ${config.DEBUG_MODE}
  }
};`;

    fs.writeFileSync(
      path.join(testnetRoot, 'graphchain-explorer', 'js', 'config.js'),
      graphchainConfig
    );

    // Generate Nexus Portal config
    const nexusConfig = `// KNIRVTESTNET Nexus Portal Configuration
// Auto-generated by load-endpoints.js
// Environment: ${config.DEPLOYMENT_ENV}

window.NEXUS_CONFIG = {
  environment: '${config.DEPLOYMENT_ENV}',
  apiEndpoints: {
    nexus_gui: '${endpoints.KNIRVNEXUS_GUI_API || endpoints.KNIRVNEXUS_API}',
    nexus_dve: '${endpoints.KNIRVNEXUS_DVE_API}',
    nexus_validation: '${endpoints.KNIRVNEXUS_VALIDATION_API}',
    chain: '${endpoints.KNIRVCHAIN_API}',
    oracle: '${endpoints.KNIRVORACLE_API}',
    router: '${endpoints.KNIRVROUTER_API}'
  },
  features: {
    testnetMode: ${config.TESTNET_MODE},
    debugMode: ${config.DEBUG_MODE},
    enableMockData: false
  }
};`;

    // Create NEXUS config directory if it doesn't exist
    const nexusConfigDir = path.join(testnetRoot, 'data', 'knirvnexus', 'portal', 'public');
    if (!fs.existsSync(nexusConfigDir)) {
      fs.mkdirSync(nexusConfigDir, { recursive: true });
    }

    fs.writeFileSync(
      path.join(nexusConfigDir, 'config.js'),
      nexusConfig
    );

    // Set environment variables for Render build
    Object.entries({ ...endpoints, ...config }).forEach(([key, value]) => {
      process.env[key] = value;
    });

    console.log('✅ Configuration files generated successfully');
    console.log('📁 Generated:');
    console.log('   - graphchain-explorer/js/config.js');
    console.log('   - data/knirvnexus/portal/public/config.js');
    
  } catch (error) {
    console.error('❌ Error generating config files:', error.message);
    process.exit(1);
  }
}

function displayEndpoints(endpoints, config) {
  console.log('\n🌐 Active Endpoints:');
  console.log('==================');
  Object.entries(endpoints).forEach(([key, value]) => {
    console.log(`   ${key}: ${value}`);
  });
  
  console.log('\n⚙️  Configuration:');
  console.log('==================');
  Object.entries(config).forEach(([key, value]) => {
    console.log(`   ${key}: ${value}`);
  });
  console.log('');
}

// Main execution
if (require.main === module) {
  const environment = process.argv[2] || process.env.NODE_ENV || 'development';
  
  console.log('🚀 KNIRVTESTNET Endpoint Loader');
  console.log('================================');
  
  const { endpoints, config } = loadEndpoints(environment);
  generateConfigFiles(endpoints, config);
  displayEndpoints(endpoints, config);
  
  console.log('🎉 Endpoint loading completed successfully!');
}

module.exports = { loadEndpoints, generateConfigFiles };
