#!/usr/bin/env node

/**
 * KNIRVGATEWAY Endpoint Loader
 * 
 * This script reads endpoints.yaml (if it exists) and sets up environment variables
 * for production deployment. For testnet, it uses .env.testnet instead.
 * 
 * Usage:
 *   node scripts/load-endpoints.js [environment]
 *   
 * Environment:
 *   - production: Reads config/endpoints.yaml
 *   - testnet: Uses .env.testnet
 *   - development: Uses default development endpoints
 */

import fs from 'fs';
import path from 'path';
import yaml from 'js-yaml';
import { fileURLToPath } from 'url';

// ES module compatibility
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Default development endpoints
const DEFAULT_ENDPOINTS = {
  KNIRVCHAIN_API: 'http://localhost:8080',
  KNIRVGRAPH_API: 'http://localhost:8081',
  KNIRVNEXUS_API: 'http://localhost:8082',
  KNIRVORACLE_API: 'http://localhost:1317',
  KNIRVROUTER_API: 'http://localhost:8086',
  KNIRVANA_API: 'http://localhost:3000',
  KNIRVANA_INTERACTIVE_GRAPH: 'http://localhost:3000'
};

function loadEndpoints(environment = 'development') {
  const gatewayRoot = path.resolve(__dirname, '..');
  let endpoints = { ...DEFAULT_ENDPOINTS };
  let config = {
    NODE_ENV: environment,
    DEPLOYMENT_ENV: environment,
    TESTNET_MODE: environment === 'testnet',
    DEBUG_MODE: environment !== 'production',
    ENABLE_CORS: environment !== 'production'
  };

  console.log(`🔧 Loading endpoints for environment: ${environment}`);

  try {
    if (environment === 'production') {
      // Load from endpoints.yaml for production
      const endpointsFile = path.join(gatewayRoot, 'config', 'endpoints.yaml');
      
      if (fs.existsSync(endpointsFile)) {
        console.log('📄 Reading production endpoints from config/endpoints.yaml');
        const yamlContent = fs.readFileSync(endpointsFile, 'utf8');
        const yamlData = yaml.load(yamlContent);
        
        if (yamlData && yamlData.endpoints) {
          endpoints = { ...endpoints, ...yamlData.endpoints };
          console.log('✅ Production endpoints loaded successfully');
        }
        
        if (yamlData && yamlData.config) {
          config = { ...config, ...yamlData.config };
        }
      } else {
        console.warn('⚠️  Production endpoints.yaml not found - using defaults');
        console.warn('   Run "make generate-production-endpoints" first');
      }
      
    } else if (environment === 'testnet') {
      // Load from .env.testnet for testnet
      const testnetEnvFile = path.join(gatewayRoot, '.env.testnet');
      
      if (fs.existsSync(testnetEnvFile)) {
        console.log('📄 Reading testnet endpoints from .env.testnet');
        const envContent = fs.readFileSync(testnetEnvFile, 'utf8');
        
        // Parse .env format
        envContent.split('\n').forEach(line => {
          const trimmed = line.trim();
          if (trimmed && !trimmed.startsWith('#')) {
            const [key, ...valueParts] = trimmed.split('=');
            const value = valueParts.join('=');
            if (key && value) {
              if (key in endpoints) {
                endpoints[key] = value;
              } else {
                config[key] = value;
              }
            }
          }
        });
        
        console.log('✅ Testnet endpoints loaded successfully');
      } else {
        console.warn('⚠️  Testnet .env.testnet not found - using defaults');
        console.warn('   Run testnet deployment first');
      }
    }
    
  } catch (error) {
    console.error('❌ Error loading endpoints:', error.message);
    console.log('📋 Using default development endpoints');
  }

  return { endpoints, config };
}

