// Event types
const (
	EventComputeStart = 1
	EventComputeEnd   = 2
	EventBatchStart   = 3
	EventBatchEnd     = 4
	EventError        = 5
)

// HashEvent represents an event from eBPF
type HashEvent struct {
	Timestamp uint64
	PID       uint32
	TID       uint32
	EventType uint8
	DataSize  uint32
	LatencyNs uint64
	BatchSize uint32
	Comm      [16]byte
}

// Tracer manages eBPF programs for ASIC monitoring
type Tracer struct {
	objs   *ebpfObjects
	links  []link.Link
	reader *ringbuf.Reader
	events chan HashEvent
	stopCh chan struct{}
	wg     sync.WaitGroup
	mu     sync.Mutex
}

// ebpfObjects holds eBPF maps and programs (auto-generated by bpf2go)
type ebpfObjects struct {
	Programs ebpfPrograms
	Maps     ebpfMaps
}

type ebpfPrograms struct {
	TraceComputeStart *ebpf.Program `ebpf:"trace_compute_start"`
	TraceComputeEnd   *ebpf.Program `ebpf:"trace_compute_end"`
	TraceBatchStart   *ebpf.Program `ebpf:"trace_batch_start"`
	TraceBatchEnd     *ebpf.Program `ebpf:"trace_batch_end"`
}

type ebpfMaps struct {
	ComputeStartTimes *ebpf.Map `ebpf:"compute_start_times"`
	Events            *ebpf.Map `ebpf:"events"`
	Stats             *ebpf.Map `ebpf:"stats"`
}

// HashStats represents statistics from eBPF
type HashStats struct {
	TotalRequests  uint64
	TotalBytes     uint64
	TotalLatencyNs uint64
	PeakLatencyNs  uint64
	ErrorCount     uint64
}

